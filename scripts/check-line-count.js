/* Fail the check when an actively maintained source file exceeds 600 lines. */
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const LIMIT = 600;
const CODE_EXTENSIONS = new Set([
  '.cjs', '.css', '.html', '.js', '.json', '.jsx', '.mjs', '.py', '.ps1',
  '.sh', '.svg', '.ts', '.tsx', '.vue', '.xml',
]);
const EXCLUDED_DIRS = new Set(['.git', 'build', 'coverage', 'dist', 'node_modules', 'vendor']);
const GENERATED_MARKER = '@generated by scripts/build-sources.js';

function lineCount(source) {
  if (!source) return 0;
  const lines = source.split(/\r\n|\n|\r/);
  return lines[lines.length - 1] === '' ? lines.length - 1 : lines.length;
}

function walk(directory) {
  const entries = fs.readdirSync(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    if (entry.isDirectory() && !EXCLUDED_DIRS.has(entry.name)) {
      files.push(...walk(path.join(directory, entry.name)));
    } else if (entry.isFile() && CODE_EXTENSIONS.has(path.extname(entry.name).toLowerCase())) {
      files.push(path.join(directory, entry.name));
    }
  }
  return files;
}

const findings = walk(ROOT)
  .map((file) => {
    const source = fs.readFileSync(file, 'utf8');
    const relative = path.relative(ROOT, file).replaceAll(path.sep, '/');
    return {
      file: relative,
      lines: lineCount(source),
      generated: source.split(/\r\n|\n|\r/).slice(0, 5).join('\n').includes(GENERATED_MARKER),
    };
  })
  .sort((a, b) => b.lines - a.lines || a.file.localeCompare(b.file));

for (const finding of findings) {
  const status = finding.generated ? 'generated/excluded' : finding.lines > LIMIT ? 'FAIL' : 'ok';
  console.log(`${String(finding.lines).padStart(4)} ${status.padEnd(17)} ${finding.file}`);
}

const violations = findings.filter((finding) => !finding.generated && finding.lines > LIMIT);
if (violations.length) {
  console.error(`\n${violations.length} actively maintained file(s) exceed ${LIMIT} lines.`);
  process.exitCode = 1;
}
